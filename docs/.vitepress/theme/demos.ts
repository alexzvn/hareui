import { ref, type Component } from 'vue'

const loaders = import.meta.glob<{ default: Component }>('../../demos/**/*.vue')

const sourceLoaders = import.meta.glob<string>('../../demos/**/*.vue', {
  query: '?raw',
  import: 'default',
})

/** Lazy loader for `docs/demos/<name>.vue`, or `undefined` when there's no such demo. */
export const demoLoader = (name: string) => {
  return loaders[`../../demos/${name}.vue`]
}

/** Lazy loader for the source text of `docs/demos/<name>.vue`, or `undefined` when there's no such demo. */
export const demoSourceLoader = (name: string) => {
  return sourceLoaders[`../../demos/${name}.vue`]
}

/** The standalone page of a demo (generated by `docs/preview/[name].paths.ts`; `name` may contain slashes). */
export const demoPreviewPath = (name: string) => {
  return `/preview/${name}`
}

export type PreviewTheme = 'light' | 'dark'

/**
 * Theme of the inline preview last interacted with, when it differs from the docs theme: the docs-wide toast region
 * (Layout.vue) takes it, so a `toast()` fired from a dark preview on a light page shows dark.
 */
export const previewOverlayTheme = ref<PreviewTheme>()

/** `postMessage` payload a preview page sends its parent once the demo has rendered. */
export type PreviewReadyMessage = {
  type: 'hareui-preview-ready'
}

export const isPreviewReadyMessage = (data: unknown): data is PreviewReadyMessage => {
  return (
    typeof data === 'object' &&
    data !== null &&
    'type' in data &&
    data.type === 'hareui-preview-ready'
  )
}
